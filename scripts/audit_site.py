#!/usr/bin/env python3
"""Static quality audit for Imsfrane GitHub Pages. Informational; no site mutations.\nRun after localization fixes to verify the full current release.\n"""
from pathlib import Path
from html.parser import HTMLParser
from urllib.parse import unquote, urlsplit
from collections import Counter
import json, re
ROOT=Path(".")
LOCALES={"ar","en","es","fr"}
class Page(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.attrs=[];self.lang="";self.title=False;self.canonical="";self.description=""
    def handle_starttag(self,tag,attrs):
        d=dict(attrs)
        if tag=="html": self.lang=d.get("lang","")
        if tag=="title":self.title=True
        if tag=="link" and d.get("rel")=="canonical":self.canonical=d.get("href","")
        if tag=="meta" and d.get("name")=="description":self.description=d.get("content","")
        for attr in ("href","src"):
            if attr in d:self.attrs.append((attr,d[attr]))
def candidate(link,base):
    if link.startswith(("mailto:","tel:","data:","javascript:","#","//")):return None
    bits=urlsplit(link)
    if bits.scheme and bits.netloc not in ("imsfrane.com","www.imsfrane.com"):return None
    if bits.scheme and bits.scheme not in ("http","https"):return None
    path=unquote(bits.path)
    if not path:return None
    if path.startswith("/"):candidate=ROOT/path.lstrip("/")
    else:candidate=base.parent/path
    try: candidate=candidate.resolve().relative_to(ROOT.resolve())
    except ValueError:return None
    p=ROOT/candidate
    if p.is_dir():p=p/"index.html"
    return p
pages=list(ROOT.rglob("*.html"))
problems=[]
c=Counter()
for p in pages:
    rel=p.as_posix();parts=p.parts
    if not parts or parts[0] not in LOCALES:continue
    # Redirect stubs are deliberately legacy URL aliases.
    raw=p.read_text(encoding="utf-8",errors="replace")
    if "IMSFRANE_CLEAN_URL_REDIRECT" in raw: continue
    c["canonical_pages"]+=1
    doc=Page()
    try:doc.feed(raw)
    except Exception as e:
        problems.append((rel,"html_parse",str(e)));continue
    if doc.lang!=parts[0]:problems.append((rel,"language",doc.lang))
    if not doc.description:problems.append((rel,"seo_description","missing"))
    if not doc.canonical:problems.append((rel,"canonical","missing"))
    if parts[0]=="ar" and doc.description and re.search(r"\b(?:Histoires|Comment|Découvrez|Conseils|Guide|Explorez)\b",doc.description):
        problems.append((rel,"seo_language","French description on Arabic page"))
    if parts[0]=="es" and doc.description and re.search(r"\b(?:Histoires|Comment rejoindre|Découvrez|Conseils pratiques)\b",doc.description):
        problems.append((rel,"seo_language","French description on Spanish page"))
    for attr,link in doc.attrs:
        dest=candidate(link,p)
        if dest is not None and not dest.exists() and not dest.with_suffix(".html").exists():
            # Skip ordinary links that could be generated by scripts or query APIs.
            if len(problems)<3000:problems.append((rel,"missing_local_"+attr,link))
c["issues"]=len(problems)
print("IMSFRANE SITE AUDIT")
print(json.dumps(dict(c),ensure_ascii=False))
for typ,num in Counter(t for _,t,_ in problems).most_common():print(typ,num)
print("First 150 issues:")
for rel,typ,detail in problems[:150]:print(rel,"::",typ,"::",detail)
Path("site-audit-report.json").write_text(json.dumps({"summary":dict(c),"issues":[{"file":a,"type":b,"detail":d} for a,b,d in problems]},ensure_ascii=False,indent=2),encoding="utf-8")
